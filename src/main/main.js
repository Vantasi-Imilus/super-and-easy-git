// Electron main process: window lifecycle, app:// protocol, single instance.
// All engine work happens in the main process; the renderer is sandboxed and
// only talks to us through the contextBridge API in src/preload.cjs.
import { app, BrowserWindow, net, protocol } from 'electron';
import fsp from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { registerIpc } from './ipc.js';
import { TaskStore } from './tasks.js';
import { Settings } from './settings.js';
import { EngineHost } from './engine-host.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const RENDERER_DIR = path.join(ROOT, 'src', 'renderer');

// Chromium refuses to load ES modules over file://, so the renderer is served
// through a privileged custom scheme instead. Dev and production behave the
// same way, and no dev server is needed.
protocol.registerSchemesAsPrivileged([
  {
    scheme: 'app',
    privileges: { standard: true, secure: true, supportFetchAPI: true, stream: true, codeCache: true },
  },
]);

function handleAppRequest(request) {
  if (request.method !== 'GET') {
    return new Response('Method Not Allowed', { status: 405 });
  }
  let rel;
  try {
    rel = decodeURIComponent(new URL(request.url).pathname);
  } catch {
    return new Response('Bad Request', { status: 400 });
  }
  if (rel === '' || rel === '/') rel = '/index.html';
  const filePath = path.normalize(path.join(RENDERER_DIR, rel));
  if (filePath !== RENDERER_DIR && !filePath.startsWith(RENDERER_DIR + path.sep)) {
    return new Response('Forbidden', { status: 403 });
  }
  return net.fetch(pathToFileURL(filePath).toString()).catch(
    () => new Response('Not Found', { status: 404 }),
  );
}

let mainWindow = null;

// Normalize the console-message event across Electron versions (older releases
// pass positional arguments, newer ones a details object).
function consoleDetails(args) {
  const d = args[1];
  if (d && typeof d === 'object' && 'message' in d) {
    return { level: d.level, message: d.message, source: d.sourceId, line: d.lineNumber };
  }
  return { level: args[1], message: args[2], source: args[4], line: args[3] };
}

function isErrorLevel(level) {
  return level === 'error' || level === 3;
}

function createWindow() {
  const iconPath = path.join(ROOT, 'assets', 'icon.png');
  const win = new BrowserWindow({
    width: 1120,
    height: 760,
    minWidth: 900,
    minHeight: 580,
    backgroundColor: '#0e1116',
    show: false,
    autoHideMenuBar: true,
    title: '超级易用 Git 下载器',
    // assets/icon.png is generated by `npm run icon`; a fresh clone may not have it.
    ...(existsSync(iconPath) ? { icon: iconPath } : {}),
    webPreferences: {
      preload: path.join(__dirname, '..', 'preload.cjs'),
      contextIsolation: true,
      sandbox: true,
      nodeIntegration: false,
      spellcheck: false,
    },
  });
  win.once('ready-to-show', () => win.show());
  // The renderer never navigates and never opens windows.
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.webContents.on('will-navigate', (event) => event.preventDefault());

  let rendererErrors = 0;
  const smoke = Boolean(process.env.GITDL_SMOKE);
  if (smoke || process.env.GITDL_DEV) {
    win.webContents.on('console-message', (...args) => {
      const info = consoleDetails(args);
      if (isErrorLevel(info.level)) rendererErrors += 1;
      if (smoke || process.env.GITDL_DEV) {
        console.log(`[renderer:${info.level}] ${info.message} (${info.source}:${info.line})`);
      }
    });
    win.webContents.on('preload-error', (_event, preloadPath, error) => {
      rendererErrors += 1;
      console.error(`[preload-error] ${preloadPath}: ${error}`);
    });
    win.webContents.on('did-fail-load', (_event, code, description) => {
      rendererErrors += 1;
      console.error(`[did-fail-load] ${code} ${description}`);
    });
  }
  if (smoke) {
    // Headless acceptance check: the renderer must have booted, the bridge API
    // must be present, and no console errors may have been logged.
    win.webContents.once('did-finish-load', () => {
      setTimeout(async () => {
        let detail;
        try {
          detail = await win.webContents.executeJavaScript(`JSON.stringify({
            tabs: document.querySelectorAll('.tab').length,
            view: document.querySelector('.view-root > *')?.className ?? null,
            bridge: typeof window.gitdl?.appInfo === 'function' && typeof window.gitdl?.ping === 'function' && typeof window.gitdl?.detectGit === 'function',
            status: document.getElementById('status-text')?.textContent ?? '',
            badge: document.getElementById('git-badge')?.textContent ?? ''
          })`);
        } catch (err) {
          detail = `检查失败: ${err.message}`;
          rendererErrors += 1;
        }
        const parsed = (() => { try { return JSON.parse(detail); } catch { return null; } })();
        const ok = rendererErrors === 0 && parsed?.tabs === 4 && parsed?.bridge === true && parsed?.badge.includes('git:');
        console.log(`[smoke] ${detail}`);
        console.log(ok ? 'GITDL_SMOKE_OK' : `GITDL_SMOKE_FAIL rendererErrors=${rendererErrors}`);
        app.exit(ok ? 0 : 1);
      }, 1500);
    });
  }
  if (process.env.GITDL_SHOT) {
    // Documentation aid (`npm run screenshot`): save a PNG of the real UI.
    win.webContents.once('did-finish-load', () => {
      setTimeout(async () => {
        try {
          // Fill the form so the screenshot shows a realistic state.
          await win.webContents.executeJavaScript(`
            (() => {
              const inputs = document.querySelectorAll('.view input[type=text]');
              if (inputs[0]) inputs[0].value = 'https://github.com/git/git';
              if (inputs[1]) inputs[1].value = 'D:\\\\Downloads';
              return true;
            })()
          `);
          const image = await win.webContents.capturePage();
          const file = path.resolve(ROOT, process.env.GITDL_SHOT);
          await fsp.mkdir(path.dirname(file), { recursive: true });
          await fsp.writeFile(file, image.toPNG());
          console.log(`GITDL_SHOT_OK ${file}`);
        } catch (err) {
          console.error(`GITDL_SHOT_FAIL ${err.message}`);
        }
        app.exit(0);
      }, 2500);
    });
  }
  if (process.env.GITDL_DEV) win.webContents.openDevTools({ mode: 'detach' });
  win.loadURL('app://bundle/index.html');
  win.on('closed', () => {
    mainWindow = null;
  });
  return win;
}

if (!app.requestSingleInstanceLock()) {
  app.quit();
} else {
  app.on('second-instance', () => {
    if (mainWindow) {
      if (mainWindow.isMinimized()) mainWindow.restore();
      mainWindow.focus();
    }
  });

  app.whenReady().then(async () => {
    app.setAppUserModelId('io.github.vantasi-imilus.super-and-easy-git');
    protocol.handle('app', handleAppRequest);

    const store = await new TaskStore(path.join(app.getPath('userData'), 'tasks.json')).load();
    const settings = await new Settings(path.join(app.getPath('userData'), 'settings.json')).load();
    const host = new EngineHost({
      store,
      settings,
      broadcast: (payload) => {
        for (const win of BrowserWindow.getAllWindows()) {
          win.webContents.send('engine:event', payload);
        }
      },
    });
    registerIpc({ host, settings });

    mainWindow = createWindow();

    app.on('activate', () => {
      if (BrowserWindow.getAllWindows().length === 0) mainWindow = createWindow();
    });
  });

  app.on('window-all-closed', () => {
    if (process.platform !== 'darwin') app.quit();
  });
}
